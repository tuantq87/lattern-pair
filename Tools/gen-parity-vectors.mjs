// Regenerates Assets/_Tests/EditMode/PrototypeVectors.cs from Prototype/index.html.
// The C# Core must reproduce the HTML5 prototype value for value (same seed => same planet),
// so the expected values in the EditMode tests come straight from the prototype's own functions.
//
// Usage: node Tools/gen-parity-vectors.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lines = readFileSync(join(root, 'Prototype/index.html'), 'utf8').split('\n');
const indexOf = marker => {
  const i = lines.findIndex(l => l.includes(marker));
  if (i < 0) throw new Error(`Marker not found in Prototype/index.html: ${marker}`);
  return i;
};

// Only the pure functions: mulberry32, clamp/lerp, the colour helpers and the planet generator.
const source = [
  lines[indexOf('function mulberry32(')],
  lines[indexOf('const clamp = ')],
  ...lines.slice(indexOf('=== colour helpers'), indexOf('=== assets')),
].join('\n');

const probe = `
const r1 = mulberry32(1);
const hueCases = [['#1B2A49', 0.1, 0], ['#F49AC1', -0.035, 0.018], ['#FFD66B', 0.5, -0.2], ['#2A1633', 0.9, 0.05]];
const mixCases = [['#1B2A49', '#000000', 0.25], ['#2E6B5E', '#FFD66B', 0.5], ['#F7B267', '#ffffff', 0.4]];
const planet = p => ({ seed: p.seed, name: p.name, fam: p.fam, hj: p.hj, pal: p.pal, dens: p.dens, wind: p.wind, crit: p.crit,
  dark: p.dark, tonic: p.tonic, lead: p.lead, kind: p.kind, moon: p.moon, pX: p.pX, pS: p.pS });
JSON.stringify({
  rngSeed1: [r1(), r1(), r1(), r1(), r1()],
  hue: hueCases.map(([c, dh, dl]) => [c, dh, dl, hueShift(c, dh, dl)]),
  mix: mixCases.map(([a, b, t]) => [a, b, t, mixc(a, b, t)]),
  planets: [...CAT_SEEDS, 1, 99999, 123456789].map(makePlanet).map(planet),
  tiers: [0, 1, 2, 5, 9].map(t => ({ tier: t, ...tierPal(CAT[0], t) })),
});`;

const v = JSON.parse(vm.runInNewContext(source + probe, { Math, JSON }));

const num = x => (Number.isInteger(x) ? `${x}.0` : String(x));
const str = s => JSON.stringify(s);
const tierFields = ['deep', 'mid', 'warm', 'light', 'skyTop', 'skyMid', 'skyBot', 'far', 'mid2', 'near', 'wall', 'spike', 'planet', 'fog'];

const cs = `// <auto-generated>
// Generated by Tools/gen-parity-vectors.mjs from Prototype/index.html. Do not edit by hand.
// </auto-generated>
namespace LanternPair.Tests
{
    public static class PrototypeVectors
    {
        public sealed class Planet
        {
            public int Seed; public string Name; public int Family; public double HueJitter; public string[] Palette;
            public double Density; public double Wind; public double CrawlerRate; public double DarknessSpeed;
            public int Tonic; public string Lead; public string Kind; public bool Moon; public double PlanetX; public double PlanetScale;
            public override string ToString() => Name + " #" + Seed;
        }

        public static readonly double[] RngSeed1 = { ${v.rngSeed1.map(num).join(', ')} };

        /// <summary>{ hex, hueDelta, lightDelta, expected }</summary>
        public static readonly object[][] HueShifts =
        {
${v.hue.map(([c, dh, dl, e]) => `            new object[] { ${str(c)}, ${num(dh)}, ${num(dl)}, ${str(e)} },`).join('\n')}
        };

        /// <summary>{ a, b, t, expected }</summary>
        public static readonly object[][] Mixes =
        {
${v.mix.map(([a, b, t, e]) => `            new object[] { ${str(a)}, ${str(b)}, ${num(t)}, ${str(e)} },`).join('\n')}
        };

        public static readonly Planet[] Planets =
        {
${v.planets.map(p => `            new Planet { Seed = ${p.seed}, Name = ${str(p.name)}, Family = ${p.fam}, HueJitter = ${num(p.hj)}, Palette = new[] { ${p.pal.map(str).join(', ')} },
                Density = ${num(p.dens)}, Wind = ${num(p.wind)}, CrawlerRate = ${num(p.crit)}, DarknessSpeed = ${num(p.dark)},
                Tonic = ${p.tonic}, Lead = ${str(p.lead)}, Kind = ${str(p.kind)}, Moon = ${p.moon}, PlanetX = ${num(p.pX)}, PlanetScale = ${num(p.pS)} },`).join('\n')}
        };

        /// <summary>Tier palettes of catalog planet #4127: { tier, ${tierFields.join(', ')} }</summary>
        public static readonly object[][] Tiers =
        {
${v.tiers.map(t => `            new object[] { ${t.tier}, ${tierFields.map(f => str(t[f])).join(', ')} },`).join('\n')}
        };
    }
}
`;

const out = join(root, 'Assets/_Tests/EditMode/PrototypeVectors.cs');
writeFileSync(out, cs);
console.log(`Wrote ${out} (${v.planets.length} planets, ${v.tiers.length} tiers)`);
